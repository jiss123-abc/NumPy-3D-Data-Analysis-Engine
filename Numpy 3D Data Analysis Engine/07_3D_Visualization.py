import os
os.makedirs("visualizations", exist_ok=True)
import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D
data = np.load("datasets/sensor_data.npy")
temperature = data[:,:,0]
days = np.arange(1, 31)
for i in range(5):
    plt.plot(days, temperature[i], label=f'Station {i+1}', marker='o')
    plt.title("Temperature Readings")
    plt.xlabel("Days")
    plt.ylabel("Temperature (°C)")
    plt.grid(True)
plt.legend()
plt.savefig("visualizations/temperature_line.png")
plt.show()
avg_temperature=np.mean(temperature, axis=1)
plt.bar(np.arange(1, 6), avg_temperature)
plt.title("Average Temperature by Station")
plt.xlabel("Stations")
plt.ylabel("Average Temperature (°C)")
plt.grid(axis='y')
plt.legend()
plt.savefig("visualizations/temperature_bar.png")
plt.show()
humidity=data[:,:,1]
flattened_humidity=humidity.flatten()
flattened_temperature=temperature.flatten()
plt.scatter(flattened_temperature, flattened_humidity)
plt.title("Temperature vs. Humidity")
plt.xlabel("Temperature (°C)")
plt.ylabel("Humidity (%)")
plt.grid(True)
plt.savefig("visualizations/temperature_humidity_scatter.png")
plt.show()
plt.hist(flattened_temperature, bins=10)
plt.title("Temperature Distribution")
plt.xlabel("Temperature (°C)")
plt.ylabel("Frequency")
plt.grid(True)
plt.savefig("visualizations/temperature_histogram.png")
plt.show()
fig=plt.figure()
ax=fig.add_subplot(111, projection='3d')
stations=np.arange(1, 6)
days=np.arange(1, 31)
X,Y=np.meshgrid(days, stations)
Z=temperature
ax.scatter(X, Y, Z)
ax.set_title("3D Temperature Distribution Across Stations")
ax.set_xlabel("Days")
ax.set_ylabel("Stations")
ax.set_zlabel("Temperature (°C)")
plt.savefig("visualizations/3d_temperature_distribution.png", dpi=300)
plt.show()